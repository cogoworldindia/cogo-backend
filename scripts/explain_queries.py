"""EXPLAIN ANALYZE the feed and matches queries exactly as journey-service builds them
(spec §11: commit the plans in docs/perf/). Runs inside the journey container:

    make explain          (after make seed or make load-seed)

Captures the SQL the app sends (same text, same parameters) and re-runs it under
EXPLAIN (ANALYZE, BUFFERS). Prints Markdown on stdout. Optional arguments: viewer id and
journey id; by default the journey with the most matches and its host.
"""

import asyncio
import sys
from collections.abc import Awaitable, Callable
from datetime import UTC, datetime
from typing import Any
from uuid import UUID

from cogo_common.appconfig import AppConfig
from cogo_common.db import Database
from cogo_common.redis import create_redis
from sqlalchemy import event, func, select
from sqlalchemy.ext.asyncio import AsyncSession

from app.config import get_settings
from app.feed import FeedFilters, feed_page
from app.matches import matches_page
from app.models import Journey, JourneyMatch, JourneyStatus, UserProjection


async def main() -> int:
    settings = get_settings()
    db = Database(settings.DATABASE_URL, pool_size=1, max_overflow=0)
    config = AppConfig.from_settings(settings, create_redis(settings.REDIS_URL))
    feed_cfg, matching_cfg = await config.get("feed"), await config.get("matching")
    radius_km = float((await config.get("filter"))["radius_km"])
    captured: list[tuple[str, Any]] = []

    @event.listens_for(db.engine.sync_engine, "before_cursor_execute")
    def capture(_conn: Any, _cursor: Any, statement: str, params: Any, *_: Any) -> None:
        captured.append((statement, params))

    async def explain(title: str, run: Callable[[AsyncSession], Awaitable[list[Any]]]) -> None:
        async with db.sessionmaker() as session:
            captured.clear()
            rows = await run(session)
            statement, params = captured[-1]  # the page query (the viewer lookup comes first)
            conn = await session.connection()
            plan = await conn.exec_driver_sql("EXPLAIN (ANALYZE, BUFFERS) " + statement, params)
            print(f"## {title}\n\n{len(rows)} rows returned.\n\n```")
            print("\n".join(r[0] for r in plan.all()))
            print("```\n")

    async with db.sessionmaker() as session:
        sizes = {
            "users": await session.scalar(select(func.count()).select_from(UserProjection)),
            "journeys": await session.scalar(select(func.count()).select_from(Journey)),
            "upcoming": await session.scalar(
                select(func.count()).where(Journey.status == JourneyStatus.UPCOMING.value)
            ),
            "journey_matches": await session.scalar(
                select(func.count()).select_from(JourneyMatch)
            ),
        }
        busiest = (
            await session.execute(
                select(JourneyMatch.journey_id, Journey.user_id)
                .join(Journey, Journey.id == JourneyMatch.journey_id)
                .group_by(JourneyMatch.journey_id, Journey.user_id)
                .order_by(func.count().desc())
                .limit(1)
            )
        ).one()
    journey_id = UUID(sys.argv[2]) if len(sys.argv) > 2 else busiest[0]
    viewer = UUID(sys.argv[1]) if len(sys.argv) > 1 else busiest[1]
    print("# Feed and matches query plans\n")
    print(
        f"Generated by `make explain` (scripts/explain_queries.py) on {datetime.now(UTC).date()}"
        " against the local stack's journeydb: the statements journey-service sends, re-run"
        " under EXPLAIN (ANALYZE, BUFFERS) (spec §11). The viewer is the host of the journey"
        " with the most matches.\n"
    )
    print("Data: " + ", ".join(f"{v} {k}" for k, v in sizes.items()) + ".\n")
    now = datetime.now(UTC)
    filters, limit = FeedFilters(), int(feed_cfg["page_size"]) + 1

    await explain(
        "Feed, first page",
        lambda s: feed_page(
            s, viewer, filters=filters, as_of=now, after=None, limit=limit, feed_cfg=feed_cfg,
            matching_cfg=matching_cfg, radius_km=radius_km,
        ),
    )  # fmt: skip
    await explain(
        "Matches, first page",
        lambda s: matches_page(
            s, viewer, journey_id, filters=filters, after=None, limit=limit,
            matching_cfg=matching_cfg, radius_km=radius_km, today=now.date(),
        ),
    )  # fmt: skip
    await config.close() if hasattr(config, "close") else None
    await db.dispose()
    return 0


if __name__ == "__main__":
    sys.exit(asyncio.run(main()))
